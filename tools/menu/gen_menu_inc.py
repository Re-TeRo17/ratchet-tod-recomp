#!/usr/bin/env python3
"""Regenerate src/patches/menu_opt_handler.inc: tools/menu/lua/optHandler.lua compiled to Lua 5.0 bytecode for tod.exe.

  python -I gen_menu_inc.py [OUT.inc]        (default: <repo>/src/patches/menu_opt_handler.inc)
  python -I gen_menu_inc.py --check          (exit 1 when the committed .inc is not what the .lua compiles to)

tod.exe builds the patched global_cached.psarc itself at start (src/patches/menu_archive.cpp). It needs the chunk the
way menu_patch.py's fit_chunk makes it, except that the chunk must fill the slot of the user's own archive exactly,
and the slot is only known at run time. So the stripped chunk (debug info dropped, as fit_chunk does) is stored in two
pieces, A and B, with the padding constant (type 4, u32 length, 'P'..., NUL) already counted in A's constant count but
cut out: at run time out = A + const(pad) + B, pad = slot - (len(A) + len(B)).  A+B is the chunk without padding;
a pad of 0 or 1..5 bytes cannot be filled (as in fit_chunk) and makes the run-time builder skip.
"""
import copy
import hashlib
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lua50_patch as L   # noqa: E402
import lua50c             # noqa: E402
import menu_patch as M    # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
LUA = os.path.join(HERE, "lua", "optHandler.lua")
DEFAULT_OUT = os.path.join(REPO, "src", "patches", "menu_opt_handler.inc")


def pieces():
    src = open(LUA, encoding="latin1").read()
    proto = lua50c.compile_chunk(src, "optHandler")
    q = copy.deepcopy(proto)
    M.strip_debug(q)
    base = L.dump(q)
    q2 = copy.deepcopy(q)
    q2.k.append((4, b"\0"))                       # the smallest padding constant (6 bytes)
    full = L.dump(q2)
    assert len(full) == len(base) + 6
    # the constant sits at the end of the main function's constant list: find where by dumping the head of the function
    f = q
    head = [L.wstr(f.source), L.w32(f.linedef), bytes((f.nups, f.nparams, f.vararg, f.maxstack))]
    head.append(L.w32(len(f.lines)))
    head.append(L.w32(len(f.locs)))
    head.append(L.w32(len(f.upvals)))
    for x in f.upvals:
        head.append(L.wstr(x))
    head.append(L.w32(len(f.k)))
    pre = L.HDR + L.TESTNUM + b"".join(head)
    ksz = 0
    for t, v in f.k:
        ksz += 1 + (4 if t == 3 else (4 + len(v) if t == 4 else 0))
    cut = len(pre) + ksz
    a = bytearray(full[:cut])
    assert full[cut:cut + 6] == bytes((4, 1, 0, 0, 0, 0))
    b = full[cut + 6:]
    assert bytes(a) + bytes((4, 1, 0, 0, 0, 0)) + b == full
    return bytes(a), b, hashlib.sha256(bytes(a) + b"|" + b).hexdigest()


def arr(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02X" % c for c in data[i:i + 16]) + ",")
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def render():
    a, b, h = pieces()
    return ("/* GENERATED by tools/menu/gen_menu_inc.py from tools/menu/lua/optHandler.lua -- do not edit.\n"
            " * sha256(A|B) = %s */\n" % h
            + "#define TOD_MENU_SCRIPT_ID \"%s\"\n" % h[:16]
            + arr("kOptHandlerA", a) + arr("kOptHandlerB", b))


def main(argv):
    text = render()
    if argv and argv[0] == "--check":
        cur = open(DEFAULT_OUT, encoding="latin1", newline="").read() if os.path.exists(DEFAULT_OUT) else ""
        if cur.replace("\r\n", "\n") != text:
            print("menu_opt_handler.inc is stale: run tools/menu/gen_menu_inc.py")
            return 1
        print("menu_opt_handler.inc matches optHandler.lua")
        return 0
    out = argv[0] if argv else DEFAULT_OUT
    with open(out, "w", encoding="latin1", newline="\n") as f:
        f.write(text)
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
